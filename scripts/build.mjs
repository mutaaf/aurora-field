// Builds dist/ from src/ with no dependencies: node scripts/build.mjs
//   dist/aurora-field.mjs           ES module (default export + named exports)
//   dist/aurora-field.worker.js     self-contained worker for AuroraField.offload()
//   dist/aurora-field-element.mjs   ES module that defines <aurora-field>
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const src = readFileSync(new URL('../src/aurora-field.js', import.meta.url), 'utf8');
const el = readFileSync(new URL('../src/element.js', import.meta.url), 'utf8');
const names = ['version', 'create', 'register', 'build', 'shapes', 'defaults', 'palettes', 'armour', 'offload', 'serve', 'fromPoints', 'fromSVG', 'fromImage', 'fromText', 'parsePath', 'figure', 'group', 'registerCrew', 'crew', 'poses', 'use', 'vocab', 'crewGroup', 'trades', 'stage', 'validate', 'schema', 'registerBuilder', 'agents'];
const dir = new URL('../dist/', import.meta.url);
mkdirSync(dir, { recursive: true });
const banner = '// generated by scripts/build.mjs from src/ — edit src, then npm run build\n';
writeFileSync(new URL('aurora-field.mjs', dir), banner +
  'const module = { exports: {} };\n' + src + '\nconst AuroraField = module.exports;\nexport default AuroraField;\n' +
  'export const { ' + names.join(', ') + ' } = AuroraField;\n');
writeFileSync(new URL('aurora-field.worker.js', dir), banner + src.replace('(typeof self !== \'undefined\' ? self : this', '(self') + '\nself.AuroraField.serve(self);\n');
writeFileSync(new URL('aurora-field-element.mjs', dir), banner + "import AuroraField from './aurora-field.mjs';\nif (!globalThis.AuroraField) globalThis.AuroraField = AuroraField;\n" + el + '\nexport default AuroraField;\n');
// minified: the UMD for <script> tags and CDNs, and the ES module (esbuild is a dev dependency only)
const { transformSync } = await import('esbuild');
const min = (code, format) => transformSync(code, { minify: true, target: 'es2015', format, legalComments: 'inline' }).code;
writeFileSync(new URL('aurora-field.min.js', dir), min(src));
writeFileSync(new URL('aurora-field.min.mjs', dir), min(readFileSync(new URL('aurora-field.mjs', dir), 'utf8'), 'esm'));
console.log('built dist/ (' + names.length + ' exports, minified UMD + ESM)');
